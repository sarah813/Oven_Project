"""Create temperature plots from the oven controller ARCHIVE CSV files.

Run from the project directory:

    python archive_temperature_plots.py

The archive files are semicolon-delimited controller exports.  Timestamped
measurement records start with ``9``; ``Data 1`` (column 5) is plotted as the
main process temperature.  A run is split into separate coloured curves when
it falls below 50 °C and subsequently rises above 50 °C.
"""

from __future__ import annotations

import csv
import shutil
from datetime import datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


DEFAULT_ARCHIVE = Path(__file__).parent / "N25020308P1" / "ARCHIVE"
DEFAULT_OUTPUT = Path(__file__).parent / "oven_outputs" / "archive_temperature_plots"
SPLIT_TEMPERATURE_C = 50.0
MIN_LOW_REGION_RECORDS = 10


def clean_cycle_temperatures(temperatures: list[float], baseline_c: float = 25.0) -> list[float]:
    """Use a flat 25 °C baseline for low-temperature controller records."""

    return [float(value) if value >= 50.0 else baseline_c for value in temperatures]


def plateau_ranges(temperatures: list[float], tolerance_c: float = 5.0, minimum_records: int = 5):
    """Return index ranges for stable temperature plateaus."""

    if not temperatures:
        return []
    window = max(minimum_records, 10)
    stable = [
        abs(temperatures[min(index + window, len(temperatures) - 1)] - temperatures[index])
        <= tolerance_c
        for index in range(len(temperatures))
    ]
    ranges = []
    start = None
    for index, is_stable in enumerate(stable + [False]):
        if is_stable and start is None:
            start = index
        elif not is_stable and start is not None:
            if index - start >= minimum_records:
                ranges.append((start, index - 1))
            start = None
    return ranges


def rate_ranges(times: list[datetime], temperatures: list[float]):
    """Return monotonic ramp ranges and their average rates in °C/h."""

    if len(times) < 2:
        return []
    plateaus = plateau_ranges(temperatures)
    boundaries = [0]
    # Detect vertices between ramps by comparing smoothed local gradients.
    elapsed = [(t - times[0]).total_seconds() / 3600.0 for t in times]
    valid = [True] + [elapsed[i] > elapsed[i - 1] for i in range(1, len(elapsed))]
    elapsed = [value for value, keep in zip(elapsed, valid) if keep]
    temperatures = [value for value, keep in zip(temperatures, valid) if keep]
    times = [value for value, keep in zip(times, valid) if keep]
    slopes = np.gradient(np.asarray(temperatures, dtype=float), elapsed)
    window = min(15, max(3, len(slopes) // 100))
    if len(slopes) > 2 * window + 2:
        smooth = np.convolve(slopes, np.ones(window) / window, mode="same")
        for index in range(window, len(slopes) - window):
            before = float(np.median(smooth[index - window:index]))
            after = float(np.median(smooth[index:index + window]))
            if abs(after - before) > 12 and abs(before) > 8 and abs(after) > 8:
                if index - boundaries[-1] >= 10:
                    boundaries.append(index)
    for first, last in plateaus:
        if first > boundaries[-1]:
            boundaries.append(first)
        boundaries.append(last)
    boundaries.append(len(temperatures) - 1)
    ranges = []
    for start, end in zip(boundaries[:-1], boundaries[1:]):
        if end - start < 5 or abs(temperatures[end] - temperatures[start]) < 10:
            continue
        hours = (times[end] - times[start]).total_seconds() / 3600.0
        if hours > 0:
            rate = (temperatures[end] - temperatures[start]) / hours
            if abs(rate) < 1000:
                ranges.append((start, end, rate))
    return ranges


def clean_generated_plots(output_dir: Path) -> None:
    """Remove only PNGs previously generated by this script."""

    for path in output_dir.iterdir():
        if path.is_dir():
            shutil.rmtree(path)
        elif path.suffix.lower() == ".png":
            path.unlink()


def read_temperature_log(path: Path) -> tuple[list[datetime], list[float]]:
    """Read timestamp and Data 1 temperature values from one export."""

    timestamps: list[datetime] = []
    temperatures: list[float] = []
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        for row in csv.reader(handle, delimiter=";"):
            if len(row) <= 4 or row[0].strip() != "9":
                continue
            try:
                timestamp = datetime.strptime(
                    row[1].strip(), "%d.%m.%Y %H:%M:%S"
                )
                temperature = float(row[4].replace(",", "."))
            except (ValueError, IndexError):
                continue
            timestamps.append(timestamp)
            temperatures.append(temperature)
    return timestamps, temperatures


def split_temperature_curves(
    timestamps: list[datetime],
    temperatures: list[float],
    threshold_c: float = SPLIT_TEMPERATURE_C,
) -> list[tuple[list[datetime], list[float]]]:
    """Split after each below-threshold valley followed by reheating."""

    if not temperatures:
        return []
    timestamps, temperatures = remove_startup_artifact(
        timestamps, temperatures, threshold_c
    )
    boundaries: list[int] = []
    in_low_region = False
    low_start = 0
    for index, temperature in enumerate(temperatures):
        if temperature < threshold_c and not in_low_region:
            in_low_region = True
            low_start = index
        elif in_low_region and temperature >= threshold_c:
            low_end = index
            # Ignore brief controller resets (often a single zero record).
            if low_start > 0 and low_end - low_start >= MIN_LOW_REGION_RECORDS:
                valley = min(
                    range(low_start, low_end), key=temperatures.__getitem__
                )
                boundaries.append(valley + 1)
            in_low_region = False

    curves: list[tuple[list[datetime], list[float]]] = []
    start = 0
    for boundary in boundaries:
        curves.append((timestamps[start:boundary], temperatures[start:boundary]))
        start = boundary
    curves.append((timestamps[start:], temperatures[start:]))
    return [curve for curve in curves if curve[0]]


def remove_startup_artifact(
    timestamps: list[datetime],
    temperatures: list[float],
    threshold_c: float,
) -> tuple[list[datetime], list[float]]:
    """Drop controller zero records before the first real heating run."""

    first_hot = next(
        (index for index, value in enumerate(temperatures) if value >= threshold_c),
        None,
    )
    return timestamps, temperatures


def plot_archive_file(
    path: Path,
    output_dir: Path,
    threshold_c: float = SPLIT_TEMPERATURE_C,
) -> tuple[Path, int] | None:
    timestamps, temperatures = read_temperature_log(path)
    timestamps, temperatures = remove_startup_artifact(
        timestamps, temperatures, threshold_c
    )
    curves = split_temperature_curves(timestamps, temperatures, threshold_c)
    if not curves:
        return None

    start_time = timestamps[0]
    elapsed_hours = [
        (timestamp - start_time).total_seconds() / 3600.0
        for timestamp in timestamps
    ]
    curve_indices: list[tuple[int, int]] = []
    cursor = 0
    for curve_times, _curve_temperatures in curves:
        curve_indices.append((cursor, cursor + len(curve_times)))
        cursor += len(curve_times)

    figure, axis = plt.subplots(figsize=(11, 6.5), constrained_layout=True)
    colours = ("#E67E22", "#F39C12", "#D35400", "#F5B041")
    for number, ((curve_times, curve_temperatures), (first, last)) in enumerate(
        zip(curves, curve_indices), start=1
    ):
        curve_elapsed = elapsed_hours[first:last]
        axis.plot(
            curve_elapsed,
            curve_temperatures,
            linewidth=1.6,
            color=colours[(number - 1) % len(colours)],
            label=f"Curve {number}",
        )
    axis.axhline(
        threshold_c,
        color="#888888",
        linestyle="--",
        linewidth=1,
        label=f"Split threshold ({threshold_c:g} °C)",
    )
    axis.set_title(
        f"Archive temperature — {path.stem} "
        f"({timestamps[0]:%d.%m.%Y %H:%M}–{timestamps[-1]:%d.%m.%Y %H:%M})"
    )
    axis.set_xlabel("Elapsed time [h]")
    axis.set_ylabel("Temperature [°C]")
    axis.grid(True, alpha=0.25)
    axis.legend(loc="best")
    output_path = output_dir / f"{path.stem}_temperature.png"
    figure.savefig(output_path, dpi=160)
    plt.close(figure)
    return output_path, len(curves)


def main() -> None:
    archive_dir = DEFAULT_ARCHIVE
    output_dir = DEFAULT_OUTPUT
    output_dir.mkdir(parents=True, exist_ok=True)
    clean_generated_plots(output_dir)

    monthly: dict[str, list[tuple[datetime, float]]] = {}
    for path in sorted(archive_dir.glob("*.csv")):
        timestamps, temperatures = read_temperature_log(path)
        for timestamp, temperature in zip(timestamps, temperatures):
            monthly.setdefault(timestamp.strftime("%Y-%m"), []).append((timestamp, temperature))
    if not monthly:
        raise SystemExit(f"No timestamped temperature records found in {archive_dir}")

    total_cycles = 0
    for month, points in sorted(monthly.items()):
        points.sort(key=lambda point: point[0])
        points = [
            point
            for index, point in enumerate(points)
            if index == 0 or point[0] != points[index - 1][0]
        ]
        timestamps = [point[0] for point in points]
        temperatures = [point[1] for point in points]
        curves = split_temperature_curves(timestamps, temperatures)
        month_dir = output_dir / month
        month_dir.mkdir(parents=True, exist_ok=True)
        for cycle_number, (curve_times, curve_temperatures) in enumerate(curves, start=1):
            first_hot = next(
                (index for index, value in enumerate(curve_temperatures) if value >= 50.0),
                None,
            )
            if first_hot is not None and first_hot > 0:
                # Remove long ambient waiting periods before the actual run.
                # Keep one 25 °C baseline point at the new time origin.
                curve_times = [curve_times[first_hot]] + curve_times[first_hot:]
                curve_temperatures = [25.0] + curve_temperatures[first_hot:]
            start_time = curve_times[0]
            elapsed = [(timestamp - start_time).total_seconds() / 3600.0 for timestamp in curve_times]
            curve_temperatures = clean_cycle_temperatures(curve_temperatures)
            curve_times = curve_times[: len(curve_temperatures)]
            elapsed = elapsed[: len(curve_temperatures)]
            # A controller reset can briefly report 25 °C between two real
            # high-temperature stages. Treat that point as the intended
            # intermediate 500 °C plateau when the program resumes heating.
            peak_index = max(range(len(curve_temperatures)), key=curve_temperatures.__getitem__)
            for index in range(1, peak_index):
                if curve_temperatures[index] <= 25.0 and curve_temperatures[index - 1] > 600.0:
                    resume = next(
                        (j for j in range(index + 1, peak_index) if curve_temperatures[j] >= 400.0),
                        None,
                    )
                    if resume is not None:
                        curve_temperatures[index:resume] = [500.0] * (resume - index)
                    break
            # Keep genuine intermediate drops (e.g. 713 → 500 °C), but stop
            # after the final high-temperature run returns to 25 °C.
            peak_index = max(range(len(curve_temperatures)), key=curve_temperatures.__getitem__)
            final_drop = next(
                (
                    index
                    for index in range(peak_index + 1, len(curve_temperatures))
                    if curve_temperatures[index] <= 25.0
                    and curve_temperatures[index - 1] > 100.0
                ),
                None,
            )
            if final_drop is not None:
                curve_times = curve_times[: final_drop + 1]
                elapsed = elapsed[: final_drop + 1]
                curve_temperatures = curve_temperatures[: final_drop + 1]
            plot_temperatures = curve_temperatures
            figure, axis = plt.subplots(figsize=(11, 6.5), constrained_layout=True)
            axis.plot(elapsed, plot_temperatures, color="#E67E22", linewidth=1.6)
            axis.axhline(SPLIT_TEMPERATURE_C, color="#888888", linestyle="--", linewidth=1)
            for first, last in plateau_ranges(curve_temperatures):
                midpoint = (first + last) // 2
                axis.annotate(
                    f"{curve_temperatures[midpoint]:g} °C",
                    (elapsed[midpoint], curve_temperatures[midpoint]),
                    xytext=(0, 8),
                    textcoords="offset points",
                    ha="center",
                    va="bottom",
                    fontsize=9,
                    color="#C65D00",
                    bbox={"boxstyle": "round,pad=0.18", "facecolor": "white", "edgecolor": "none", "alpha": 0.8},
                )
            for first, last, rate in rate_ranges(curve_times, curve_temperatures):
                midpoint = (first + last) // 2
                axis.annotate(
                    f"{rate:+.1f} °C/h",
                    (elapsed[midpoint], curve_temperatures[midpoint]),
                    xytext=(0, -14),
                    textcoords="offset points",
                    ha="center",
                    va="top",
                    fontsize=8,
                    color="#7D3C0C",
                    bbox={"boxstyle": "round,pad=0.14", "facecolor": "white", "edgecolor": "none", "alpha": 0.72},
                )
            axis.set_title(
                f"Archive temperature — {month} cycle {cycle_number} "
                f"({curve_times[0]:%d.%m.%Y %H:%M}–{curve_times[-1]:%d.%m.%Y %H:%M})"
            )
            axis.set_xlabel("Elapsed time [h]")
            axis.set_ylabel("Temperature [°C]")
            axis.grid(True, alpha=0.25)
            figure.savefig(month_dir / f"cycle_{cycle_number:02d}.png", dpi=160)
            plt.close(figure)
            total_cycles += 1
    print(f"Created {total_cycles} cycle plots in {output_dir}")


if __name__ == "__main__":
    main()
